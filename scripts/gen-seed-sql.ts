// Regenerates supabase/seed.sql from src/data/seed.ts
// Run: npx tsx scripts/gen-seed-sql.ts
import { writeFileSync } from "fs";
import { seedProducts } from "../src/data/seed";

const q = (s: string | null | undefined) => (s == null ? "null" : `'${String(s).replace(/'/g, "''")}'`);
const arr = (a: string[]) => `array[${a.map(q).join(",")}]::text[]`;

let sql = "-- Sample catalogue. Generated by scripts/gen-seed-sql.ts\nbegin;\n";
for (const p of seedProducts) {
  sql += `with p as (
  insert into products (slug, name, category, price, mrp, description, tags, images, try_on, try_on_image, active, featured)
  values (${q(p.slug)}, ${q(p.name)}, ${q(p.category)}, ${p.price}, ${p.mrp ?? "null"}, ${q(p.description)}, ${arr(p.tags)}, ${q(JSON.stringify(p.images))}::jsonb, ${q(p.tryOn)}, ${q(p.tryOnImage ?? null)}, ${p.active}, ${p.featured})
  on conflict (slug) do nothing
  returning id
)
insert into variants (product_id, name, swatch, sku, stock, position, try_on_image)
select p.id, v.name, v.swatch, v.sku, v.stock, v.position, v.try_on_image from p, (values
${p.variants.map((v, i) => `  (${q(v.name)}, ${q(v.swatch ?? null)}, ${q(v.sku)}, ${v.stock}, ${i}, ${q(v.tryOnImage ?? null)})`).join(",\n")}
) as v(name, swatch, sku, stock, position, try_on_image);
`;
}
sql += "commit;\n";
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log("wrote supabase/seed.sql");
